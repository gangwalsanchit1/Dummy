#!/usr/bin/env python3
"""Wakefit product list (bill of quantities) for floor 1, room by room, for the saved plan and any scenario.
Floors 1, 2 and 3 share one plan, so floors 1-3 = 3 x floor 1; a scenario with "floor": "F4" is counted once.
Ends with the whole building for the final drawings (final-floor1.json x 3 + final-floor4.json). Writes docs/wakefit-products.md.
Usage: python3 tools/product_list.py [scenario.json ...]
"""
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from units import ftin  # noqa: E402

AS = json.loads((ROOT / "model/assumptions.json").read_text())
CAT, FS = AS["wakefit_catalog"], AS["furniture_sizes"]
ORDER = ["centaur_single_bed", "orion_queen_bed", "tinker_side_table", "twill_wardrobe", "gingham_wardrobe", "cabrera_desk", "sage_desk",
         "flipper_sofa", "amata_sofa", "tv_42", "tv_40", "tv_32"]
SHORT = {"centaur_single_bed": "Centaur single bed", "orion_queen_bed": "Orion queen bed", "tinker_side_table": "Tinker bedside table",
         "twill_wardrobe": "Twill 2-door compact wardrobe", "gingham_wardrobe": "Gingham 2-door wardrobe with mirror",
         "cabrera_desk": "Cabrera study table", "sage_desk": "Sage study table (with hutch)", "amata_sofa": "AMATA sofa cum bed (Amazon, not Wakefit)",
         "flipper_sofa": "Flipper 2-seater sofa cum bed (opens to 6' x 4')", "tv_42": "Wall-mounted TV, 42-inch (any brand, not Wakefit)",
         "tv_40": "Wall-mounted TV, 40-inch (any brand, not Wakefit)", "tv_32": "Wall-mounted TV, 32-inch (any brand, not Wakefit)"}
MATTRESS = {"centaur_single_bed": "single mattress 78 x 36 in (6'-6\" x 3'-0\") to suit the Centaur",
            "orion_queen_bed": "queen mattress 78 x 60 in (6'-6\" x 5'-0\") to suit the Orion"}


def plan_rows(name, layouts, mult=3, label="Floors 1-3"):
    md = [f"## {name}", ""]
    rooms = list(layouts)
    tot = Counter()
    per = {r: Counter(i["type"] for i in layouts[r]) for r in rooms}
    for r in rooms:
        tot.update(per[r])
    students = sum(v for r in rooms for t, v in per[r].items() if t.endswith("_bed"))
    nst = {r: sum(v for t, v in per[r].items() if t.endswith("_bed")) for r in rooms}
    one = "Floor 1" if mult == 3 else "Floor 4"
    md += [f"Students: {', '.join(f'{r} {n}' for r, n in nst.items())} = **{students} per floor" + (f", {mult * students} on floors 1-3**." if mult == 3 else "**."), "",
           "| Wakefit product | Size W x D x H (cm) | Size (ft-in, W x D) | " + " | ".join(rooms) + f" | {one} |" + (f" {label} |" if mult == 3 else ""),
           "|---|---|---|" + "---|" * len(rooms) + ("---|---|" if mult == 3 else "---|")]
    for t in ORDER:
        if not tot[t]:
            continue
        c = CAT.get(t, {})
        nm = f"[{SHORT[t]}]({c['link']})" if c.get("link") else SHORT[t]
        w, d = FS[t][0], FS[t][1]
        md.append(f"| {nm} | {c.get('size_cm', '-')} | {ftin(w)} x {ftin(d)} | " + " | ".join(str(per[r][t] or "-") for r in rooms)
                  + f" | {tot[t]} |" + (f" {mult * tot[t]} |" if mult == 3 else ""))
    beds = {t: tot[t] for t in MATTRESS if tot[t]}
    md += ["", "**Also needed, not chosen yet (no size risk, they sit on or by the items above):**", ""]
    for t, n in beds.items():
        md.append(f"- Wakefit {MATTRESS[t]}: {n} per floor" + (f", {mult * n} on floors 1-3" if mult == 3 else ""))
    nd = sum(v for t, v in tot.items() if t.endswith("desk"))
    md.append(f"- Study chair, one per desk: {nd} per floor" + (f", {mult * nd} on floors 1-3" if mult == 3 else "") + " (fits the 2'-5½\" chair space shown on the plan)")
    md.append("")
    return md, tot


if __name__ == "__main__":
    plans = [("Plan A (saved): ROOM-1, ROOM-2, ROOM-3 twin, ROOM-4 luxury single; one brick wall and two doors moved",
              json.loads((ROOT / "model/furniture.json").read_text())["F1-3"])]
    for f in sys.argv[1:]:
        sc = json.loads(Path(f).read_text())
        plans.append((sc.get("name", Path(f).stem), sc["layouts"], 1 if sc.get("floor") == "F4" else 3))
    md = ["# Wakefit products placed (generated by tools/product_list.py)", "",
          "Floors 1, 2 and 3 share one plan, so floors 1-3 are three times floor 1. Floor 4 has its own plan and is counted once.", "",
          "Sizes come from the Wakefit pages the family shared or from retailer listings (wakefit.co blocks automated reading). "
          "**Confirm every size on the product page before ordering**, especially the Twill and Gingham (marked approximate).", ""]
    for name, lay, *m in plans:
        rows, _ = plan_rows(name, lay, *(m or [3]))
        md += rows
    f1, f4 = ROOT / "model/scenarios/final-floor1.json", ROOT / "model/scenarios/final-floor4.json"
    if f1.exists() and f4.exists():
        a, b = (Counter(i["type"] for r in json.loads(f.read_text())["layouts"].values() for i in r) for f in (f1, f4))
        md += ["## Whole building, final drawings (floors 1-3 x 3 + floor 4)", "",
               "| Product | Floors 1-3 | Floor 4 | Building |", "|---|---|---|---|"]
        for t in ORDER:
            if a[t] or b[t]:
                md.append(f"| {SHORT[t]} | {3 * a[t]} | {b[t]} | **{3 * a[t] + b[t]}** |")
        sa = sum(v for t, v in a.items() if t.endswith("_bed")); sb = sum(v for t, v in b.items() if t.endswith("_bed"))
        da = sum(v for t, v in a.items() if t.endswith("desk")); db = sum(v for t, v in b.items() if t.endswith("desk"))
        md += ["", f"Students: {3 * sa} on floors 1-3 + {sb} on floor 4 = **{3 * sa + sb}**. Study chairs: **{3 * da + db}**. "
               f"Mattresses: {3 * a['centaur_single_bed'] + b['centaur_single_bed']} single, {3 * a['orion_queen_bed'] + b['orion_queen_bed']} queen.", ""]
    md += ["## Where each size came from", "", "| Product | Source and status |", "|---|---|"]
    for t in ORDER:
        if t in CAT:
            md.append(f"| {SHORT[t]} | {CAT[t].get('source', CAT[t].get('status', '-'))} ({CAT[t].get('status', '-')}) |")
    (ROOT / "docs/wakefit-products.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))

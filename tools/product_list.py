#!/usr/bin/env python3
"""Wakefit product list (bill of quantities) for floor 1, room by room, for the saved plan and any scenario.
Floors 1, 2 and 3 share one plan, so floors 1-3 = 3 x floor 1. Writes docs/wakefit-products.md.
Usage: python3 tools/product_list.py [scenario.json ...]
"""
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from units import ftin  # noqa: E402

AS = json.loads((ROOT / "model/assumptions.json").read_text())
CAT, FS = AS["wakefit_catalog"], AS["furniture_sizes"]
ORDER = ["centaur_single_bed", "orion_queen_bed", "tinker_side_table", "twill_wardrobe", "gingham_wardrobe", "cabrera_desk", "sage_desk", "amata_sofa"]
SHORT = {"centaur_single_bed": "Centaur single bed", "orion_queen_bed": "Orion queen bed", "tinker_side_table": "Tinker bedside table",
         "twill_wardrobe": "Twill 2-door compact wardrobe", "gingham_wardrobe": "Gingham 2-door wardrobe with mirror",
         "cabrera_desk": "Cabrera study table", "sage_desk": "Sage study table (with hutch)", "amata_sofa": "AMATA sofa cum bed (Amazon, not Wakefit)"}
MATTRESS = {"centaur_single_bed": "single mattress 78 x 36 in (6'-6\" x 3'-0\") to suit the Centaur",
            "orion_queen_bed": "queen mattress 78 x 60 in (6'-6\" x 5'-0\") to suit the Orion"}


def plan_rows(name, layouts):
    md = [f"## {name}", ""]
    rooms = list(layouts)
    tot = Counter()
    per = {r: Counter(i["type"] for i in layouts[r]) for r in rooms}
    for r in rooms:
        tot.update(per[r])
    students = sum(v for r in rooms for t, v in per[r].items() if t.endswith("_bed"))
    nst = {r: sum(v for t, v in per[r].items() if t.endswith("_bed")) for r in rooms}
    md += [f"Students: {', '.join(f'{r} {n}' for r, n in nst.items())} = **{students} per floor, {3 * students} on floors 1-3**.", "",
           "| Wakefit product | Size W x D x H (cm) | Size (ft-in, W x D) | " + " | ".join(rooms) + " | Floor 1 | Floors 1-3 |",
           "|---|---|---|" + "---|" * len(rooms) + "---|---|"]
    for t in ORDER:
        if not tot[t]:
            continue
        c = CAT.get(t, {})
        nm = f"[{SHORT[t]}]({c['link']})" if c.get("link") else SHORT[t]
        w, d = FS[t][0], FS[t][1]
        md.append(f"| {nm} | {c.get('size_cm', '-')} | {ftin(w)} x {ftin(d)} | " + " | ".join(str(per[r][t] or "-") for r in rooms)
                  + f" | {tot[t]} | {3 * tot[t]} |")
    beds = {t: tot[t] for t in MATTRESS if tot[t]}
    md += ["", "**Also needed, not chosen yet (no size risk, they sit on or by the items above):**", ""]
    for t, n in beds.items():
        md.append(f"- Wakefit {MATTRESS[t]}: {n} per floor, {3 * n} on floors 1-3")
    nd = sum(v for t, v in tot.items() if t.endswith("desk"))
    md.append(f"- Study chair, one per desk: {nd} per floor, {3 * nd} on floors 1-3 (fits the 2'-5½\" chair space shown on the plan)")
    md.append("")
    return md, tot


if __name__ == "__main__":
    plans = [("Plan A (saved): ROOM-1, ROOM-2, ROOM-3 twin, ROOM-4 luxury single; one brick wall and two doors moved",
              json.loads((ROOT / "model/furniture.json").read_text())["F1-3"])]
    for f in sys.argv[1:]:
        sc = json.loads(Path(f).read_text())
        plans.append((sc.get("name", Path(f).stem), sc["layouts"]))
    md = ["# Wakefit products placed on floor 1 (generated by tools/product_list.py)", "",
          "Floors 1, 2 and 3 share one plan, so floors 1-3 are three times floor 1. Floor 4 is not designed yet and is not counted.", "",
          "Sizes come from the Wakefit pages the family shared or from retailer listings (wakefit.co blocks automated reading). "
          "**Confirm every size on the product page before ordering**, especially the Twill and Gingham (marked approximate).", ""]
    for name, lay in plans:
        rows, _ = plan_rows(name, lay)
        md += rows
    md += ["## Where each size came from", "", "| Product | Source and status |", "|---|---|"]
    for t in ORDER:
        if t in CAT:
            md.append(f"| {SHORT[t]} | {CAT[t].get('source', CAT[t].get('status', '-'))} ({CAT[t].get('status', '-')}) |")
    (ROOT / "docs/wakefit-products.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))

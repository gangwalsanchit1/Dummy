#!/usr/bin/env python3
"""Floor 1 against the structural drawing: where each column stands out of the walls, and what it touches.
Writes docs/structure-check.md (feet and inches). Reads model/structure.json, takeoff, furniture, mep."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from columns import columns  # noqa: E402
from units import ftin  # noqa: E402

ST = json.loads((ROOT / "model/structure.json").read_text())
sys.path.insert(0, str(Path(__file__).resolve().parent))
from takeoff import load_takeoff  # noqa: E402
fl = load_takeoff()["floors"]["F1-3"]
FU = json.loads((ROOT / "model/furniture.json").read_text())["F1-3"]
MEP = json.loads((ROOT / "model/mep.json").read_text())
NM = {"orion_queen_bed": "Orion queen bed", "tinker_side_table": "Tinker side table", "gingham_wardrobe": "Gingham wardrobe",
      "twill_wardrobe": "Twill wardrobe", "sage_desk": "Sage study table", "wall_desk": "wall desk", "centaur_single_bed": "Centaur single bed",
      "amata_sofa": "AMATA sofa"}


def ov(a, b, e=0.01):
    w, h = min(a[2], b[2]) - max(a[0], b[0]), min(a[3], b[3]) - max(a[1], b[1])
    return (w, h) if w > e and h > e else None


rows, issues = [], []
for c in columns("F1-3"):
    r = c["rect"]
    into = []
    for sp in fl["spaces"]:
        for q in sp["rects"]:
            o = ov(r, q)
            if o:
                into.append(f"{sp['name']}: {ftin(min(o))} × {ftin(max(o))}")
    furn = [f"{NM.get(it['type'], it['type'])} ({room})" for room, its in FU.items() for it in its if ov(r, it["rect"], 0.005)]
    wins = [w["id"] for w in fl["windows"] if ov(r, [w["span_x"][0], 0 if w["wall"] == "rear" else 11.6, w["span_x"][1], 0.15 if w["wall"] == "rear" else 11.75], 0.001)]
    pts = [f"{p['id']}" for p in MEP["points"] if p["storey"] == "F1" and any("column " + c["name"] + " " in i or i.endswith("column " + c["name"]) for i in p.get("issues", []))]
    if furn:
        issues.append(f"{c['name']} overlaps {', '.join(furn)}")
    if wins:
        issues.append(f"{c['name']} edge falls inside window {', '.join(wins)} (within the ±¾\" accuracy of the scaled position; confirm on site)")
    rows.append(f"| {c['name']} | {c['size']} mm | {'; '.join(into) if into else 'inside the wall line'} | "
                f"{', '.join(furn) if furn else 'clear'} | {', '.join(wins) if wins else '-'} | {', '.join(pts) if pts else 'clear'} |")

md = ["# Floor 1 against the structural drawing (generated by tools/structure_check.py)", "",
      f"Source: {ST['_source']}", "",
      f"How the columns were placed: the plinth layout on the sheet has no dimensions, so it was scaled. {ST['_fit']}. "
      "Positions are good to about ±¾\" (±0.02 m). Column sizes are from the schedule on the sheet (DRAWN). "
      "From first floor up every column is 230 mm (9\") wide. The walls on floor 1 are 150 mm (6\") thick, so most columns stand about 3⅛\" proud of the wall on the room side.", "",
      "| Column | Size (F1-F3) | Stands out into | Furniture | Window | Electrical / plumbing points |", "|---|---|---|---|---|---|"] + rows
md += ["", "## Result", ""] + ([f"- {i}" for i in issues] if issues else ["- No furniture overlaps a column. Furniture was re-fitted with the columns as solid obstacles."])
md += ["", "## Points for the structural engineer (Agharkar Consulting Engineers) and the architect", "",
       "1. **Storeys covered by the column schedule.** The schedule runs footing → plinth → first → second → third → terrace floor level: "
       "the stilt plus three floors. The architect's AFTER O.C. sheet shows the stilt plus **four** floors and a terrace. "
       "Please confirm with the structural engineer that the columns, and the footings, are designed for the fourth floor. This affects physical safety.",
       "2. **Floor beams are not on this sheet.** Only plinth beams (PB1-PB6) are drawn. AC wall sleeves (about 7'-10½\" above floor) "
       "and ceiling points still cannot be checked against beams.",
       "3. **Floor heights are not on this sheet.** No floor-to-floor height, slab thickness, sill or lintel level is given, so the "
       "assumed 9'-10\" floor-to-floor height stays ASSUMED.",
       "4. **ROOM-1 toilet:** C10 and C16 stand about 6\" into the toilet along its wall with ROOM-2. Check that the WC, geyser and "
       "pipes on that wall are set out clear of the column face.",
       "5. **Stair:** C5 and C8 stand about 3⅛\" into the stair landings at the side wall, and C7 about 3¼\" into the floor landing. "
       "Check that the clear landing width still meets the architect's stair design.",
       "6. **Lift walls C2, C3, C4** are RCC walls, 150 mm thick, and match the lift walls on the architect's plan.",
       "", "Nothing structural has been changed or sized here. Only furniture and proposed points were moved to keep clear of the columns."]
(ROOT / "docs/structure-check.md").write_text("\n".join(md) + "\n")
print("\n".join(issues) if issues else "no furniture on columns")
